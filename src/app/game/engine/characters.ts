export type StatusKind =
  | 'stun' // 気絶: 動けない
  | 'confuse' // 錯乱: 操作反転
  | 'charm' // メロメロ: 攻撃不可
  | 'blind' // 目潰し: 画面が暗くなる
  | 'root' // スタン: 移動不可(攻撃は可)
  | 'atkDown' // 攻撃力低下
  | 'defDown' // 防御力低下
  | 'bind' // 拘束: 動けない+継続ダメージ
  | 'bleed' // 出血: 継続ダメージ
  | 'burn' // 火傷: 継続ダメージ

