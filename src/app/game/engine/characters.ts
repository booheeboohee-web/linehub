export type ProjectileKind =
  | 'table' // ちゃぶ台
  | 'paper' // かまいたち
  | 'cosme' // コスメ
  | 'coin' // コイン
  | 'booger' // はなくそ
  | 'bug' // バッタ
  | 'shock' // 電光石火
  | 'car' // 車

export interface StatusApply {
  kind: StatusKind
  dur: number // 秒
}

export interface ProjectileDef {
  kind: ProjectileKind
  speed: number
  w: number
  h: number
  yOff: number // 地面からの高さ(発射位置)
  count?: number // 連射数
  interval?: number // 連射間隔(フレーム)
  pierce?: boolean
  spread?: number // 上下ばらつき
}

export type MoveType = 'strike' | 'projectile' | 'grab' | 'aura' | 'barrier' | 'taunt'

export interface MoveDef {
  name: string
  type: MoveType
  damage: number
  startup: number // フレーム
  active: number
  recovery: number
  range: number // 打撃/掴みのリーチ(px)
  hbH?: number // ヒットボックス高さ
  kb: number // ノックバック
  launch?: number // 打ち上げ
  hits?: number // 多段ヒット数
  hitInterval?: number
  status?: StatusApply // 相手に付与
  selfStatus?: StatusApply
  dot?: { dps: number; dur: number; kind: StatusKind }
  projectile?: ProjectileDef
  lunge?: { vx: number; vy?: number } // 突進系の自機移動
  meterCost?: number
  shake?: number // 画面揺れ
  banner?: boolean // 技名を大きく表示
  desc?: string
}

export type HairStyle = 'grandpa' | 'short' | 'long' | 'bob' | 'ponytail' | 'buzz' | 'twintail' | 'curl'

export interface CharDef {
  id: string
  name: string
  age: number
  sex: '男' | '女'
  heightCm: number
  weightKg: number
  typeDesc: string
  hp: number
  speed: number // 歩行速度 px/frame
  jumpV: number
  widthScale: number // 体型(横幅)
  skin: string
  hair: string
  hairRoot?: string // 根元の地毛色(染めキャラの二層表現)
  hairStyle: HairStyle
  shirt: string
  pants: string
  accent: string // テーマカラー(UI/選択画面)
  punch: MoveDef
  kick: MoveDef
  grab: MoveDef
  unique: MoveDef // 特殊攻撃ボタン
  sp1: MoveDef // 必殺技(ゲージ50)
  sp2: MoveDef // 超必殺技(ゲージ100)
  isBoss?: boolean
  isMidBoss?: boolean
  species?: 'cat' // 未指定なら人間
  furColor?: string
  furAccent?: string // 白斑・縞などの差し色
  eyeColor?: string
  catLegScale?: number // 猫の脚の長さ倍率(短足キャラ用)
  secretBuff?: boolean // 超必殺技の瞬間だけ裏設定の姿がよぎる小ネタ
}

